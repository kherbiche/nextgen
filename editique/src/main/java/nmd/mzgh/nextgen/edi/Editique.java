package nmd.mzgh.nextgen.edi;

import com.itextpdf.kernel.colors.ColorConstants;
import com.itextpdf.kernel.events.PdfDocumentEvent;
import com.itextpdf.kernel.pdf.PdfDocument;
import com.itextpdf.kernel.pdf.PdfWriter;
import com.itextpdf.layout.Document;
import com.itextpdf.layout.element.*;
import com.itextpdf.layout.properties.TextAlignment;
import com.itextpdf.layout.properties.UnitValue;
import sun.misc.IOUtils;

import java.io.FileInputStream;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.OutputStream;
import java.time.LocalDate;

public class Editique {

    private static final String FILE = "Contract.pdf";

    public static void main(String[] args) {
        try {
            createPdf(FILE);
            System.out.println("PDF created successfully: " + FILE);
            readPdfByte(FILE);
        } catch (Exception e) { e.printStackTrace(); }
    }

    public static void createPdf(String dest) throws IOException {

        PdfWriter writerOutputStream = new PdfWriter(dest);
        PdfDocument pdfDocument = new PdfDocument(writerOutputStream);
        Document document = new Document(pdfDocument);

        pdfDocument.getDocumentInfo().setTitle("N250000001");
        pdfDocument.getDocumentInfo().setAuthor("LK");
        pdfDocument.getDocumentInfo().setSubject("Contrat collectif AV Multisupport");
        pdfDocument.getDocumentInfo().setKeywords("Java, PDF, N25");
        pdfDocument.getDocumentInfo().setCreator("Lyes");

        pdfDocument.addEventHandler(PdfDocumentEvent.END_PAGE, new HeaderFooterHandler());

        addTitlePage(document);
        document.add(new AreaBreak());
        addContent(document);

        pdfDocument.close();
        writerOutputStream.close();
        document.close();

    }

    private static void addTitlePage(Document document) {
        Div div = new Div();
        Paragraph title = new Paragraph("Contrat af collectif vie multisupports N25. \n")
                .setFontSize(24)
                .setBold()
                .setTextAlignment(TextAlignment.CENTER)
                .setFontColor(ColorConstants.BLUE);
        div.add(title);

        Paragraph info = new Paragraph("Report generated by: " + System.getProperty("user.name") + ", " + LocalDate.now())
                .setFontSize(12)
                .setBold();
        div.add(info);
        document.add(div);

        Paragraph parag_desc = new Paragraph("Ce document décrit quelque chose d'important")
                .setFontSize(12)
                .setBold();
        document.add(parag_desc);

        for (int i = 0; i < 23; i++) { document.add(new Paragraph("\n")); }

        Paragraph disclaimer = new Paragraph("Ce document est une version préliminaire et n'est pas soumis à votre contrat de licence ou à aucun autre contrat.")
                .setFontSize(12)
                .setFontColor(ColorConstants.RED);
        document.add(disclaimer);
    }

    private static void addContent(Document document) {
        Paragraph chapter1 = new Paragraph("Chapitre 1")
                .setFontSize(18)
                .setBold();
        document.add(chapter1);

        Paragraph subCat1 = new Paragraph("Subcategory 1")
                .setFontSize(16)
                .setBold();
        document.add(subCat1);
        document.add(new Paragraph("Hello"));

        Paragraph subCat2 = new Paragraph("Subcategory 2")
                .setFontSize(16)
                .setBold();
        document.add(subCat2);
        document.add(new Paragraph("Paragraph 1"));
        document.add(new Paragraph("Paragraph 2"));
        document.add(new Paragraph("Paragraph 3"));

        List list = new List()
                .setSymbolIndent(12)
                .setListSymbol("\u2022")
                .setFontSize(12);
        list.add(new ListItem("First point"));
        list.add(new ListItem("Second point"));
        list.add(new ListItem("Third point"));
        document.add(list);

        for (int i = 0; i < 5; i++) { document.add(new Paragraph("\n")); }

        createTable(document);

        document.add(new Paragraph("\n"));
        Paragraph chapter2 = new Paragraph("Chapitre 2")
                .setFontSize(18)
                .setBold();
        document.add(chapter2);

        Paragraph subCat3 = new Paragraph("Subcategory")
                .setFontSize(16)
                .setBold();
        document.add(subCat3);
        document.add(new Paragraph("Message important"));
    }

    private static void createTable(Document document) {
        Table table = new Table(UnitValue.createPercentArray(new float[]{1, 1, 1})).useAllAvailableWidth();

        table.addHeaderCell(new Cell().add(new Paragraph("Header 1")
                .setTextAlignment(TextAlignment.CENTER)
                .setBackgroundColor(ColorConstants.LIGHT_GRAY)
                .setBold()));
        table.addHeaderCell(new Cell().add(new Paragraph("Header 2")
                .setTextAlignment(TextAlignment.CENTER)
                .setBackgroundColor(ColorConstants.LIGHT_GRAY)
                .setBold()));
        table.addHeaderCell(new Cell().add(new Paragraph("Header 3")
                .setTextAlignment(TextAlignment.CENTER)
                .setBackgroundColor(ColorConstants.LIGHT_GRAY)
                .setBold()));

        table.addCell("1.0");
        table.addCell("1.1");
        table.addCell("1.2");
        table.addCell("2.1");
        table.addCell("2.2");
        table.addCell("2.3");

        document.add(table);
    }

    private static void readPdfByte(String src) throws IOException {
        FileInputStream inputStream = new FileInputStream(src);
        byte[] pdfBytes = IOUtils.readAllBytes(inputStream);
        for (byte b : pdfBytes) { /*System.out.println((char) b);*/ }
        System.out.println("--------*****--------");
        OutputStream outputStream = new FileOutputStream("out.pdf");
        outputStream.write(pdfBytes);

        outputStream.close();
        inputStream.close();
    }
}
